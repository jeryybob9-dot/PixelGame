/**
 * Brickbox Royale — pixel toolkit + icon sprites (spells, gadgets, emotes, UI icons).
 *
 * The toolkit works on "rows": arrays of equal-length strings of palette chars (see palette.js).
 * Art is authored as fill colours only and `outline()` adds the 1px plum outline around the
 * silhouette, so animation frames built by moving parts always get a clean outline.
 * In `stamp()` parts, '.' keeps the pixel underneath and '_' erases it.
 */

// ---------------------------------------------------------------------------------------------
// Toolkit
// ---------------------------------------------------------------------------------------------

/**
 * Parse a multi-line block of pixel rows (blank lines and indentation ignored).
 * @param {string|TemplateStringsArray} str
 * @returns {string[]}
 */
export function px(str) {
  const s = typeof str === 'string' ? str : String.raw(str);
  return s.split('\n').map((l) => l.trim()).filter((l) => l.length > 0);
}

/** @param {number} w @param {number} h @param {string} [ch] */
export function blank(w, h, ch = '.') {
  return Array.from({ length: h }, () => ch.repeat(w));
}

/** @param {string[]} rows */
export function toCells(rows) {
  return rows.map((r) => r.split(''));
}

/** @param {string[][]} cells */
export function toRows(cells) {
  return cells.map((r) => r.join(''));
}

/**
 * Paste `part` onto `base` at (x, y). '.' in part = keep, '_' = erase.
 * @param {string[]} base @param {string[]} part @param {number} [x] @param {number} [y]
 */
export function stamp(base, part, x = 0, y = 0) {
  const out = toCells(base);
  for (let j = 0; j < part.length; j++) {
    const yy = y + j;
    if (yy < 0 || yy >= out.length) continue;
    const row = part[j];
    for (let i = 0; i < row.length; i++) {
      const ch = row[i];
      if (ch === '.') continue;
      const xx = x + i;
      if (xx < 0 || xx >= out[yy].length) continue;
      out[yy][xx] = ch === '_' ? '.' : ch;
    }
  }
  return toRows(out);
}

/**
 * Stamp several parts: list of [part, x, y].
 * @param {string[]} base @param {Array<[string[], number, number]>} parts
 */
export function stampAll(base, parts) {
  let out = base;
  for (const [p, x, y] of parts) out = stamp(out, p, x, y);
  return out;
}

/** New w x h rows with `part` placed at (x, y). */
export function place(w, h, part, x = 0, y = 0) {
  return stamp(blank(w, h), part, x, y);
}

/**
 * Add a 1px outline around every non-transparent pixel.
 * @param {string[]} rows
 * @param {{ch?: string, diag?: boolean, skip?: string}} [opts] skip = chars that do not cast an outline (glows, sparks)
 */
export function outline(rows, opts = {}) {
  const ch = opts.ch ?? 'o';
  const diag = opts.diag ?? false;
  const skip = opts.skip ?? '';
  const h = rows.length;
  const w = rows[0].length;
  const out = toCells(rows);
  const solid = (x, y) => {
    if (x < 0 || y < 0 || x >= w || y >= h) return false;
    const c = rows[y][x];
    return c !== '.' && !skip.includes(c);
  };
  for (let y = 0; y < h; y++) {
    for (let x = 0; x < w; x++) {
      if (rows[y][x] !== '.') continue;
      let hit = solid(x - 1, y) || solid(x + 1, y) || solid(x, y - 1) || solid(x, y + 1);
      if (!hit && diag) hit = solid(x - 1, y - 1) || solid(x + 1, y - 1) || solid(x - 1, y + 1) || solid(x + 1, y + 1);
      if (hit) out[y][x] = ch;
    }
  }
  return toRows(out);
}

/** Mirror horizontally. */
export function flipX(rows) {
  return rows.map((r) => r.split('').reverse().join(''));
}

/** Mirror vertically. */
export function flipY(rows) {
  return rows.slice().reverse();
}

/** Move pixels by (dx, dy), filling with '.'. Size stays the same. */
export function shift(rows, dx, dy) {
  const h = rows.length;
  const w = rows[0].length;
  return stamp(blank(w, h), rows, dx, dy);
}

/**
 * Swap chars by a map, e.g. { T: 'r', t: 'R' }.
 * @param {string[]} rows @param {Record<string,string>} map
 */
export function recolor(rows, map) {
  return rows.map((r) => r.split('').map((c) => (c in map ? map[c] : c)).join(''));
}

/**
 * Build a symmetric sprite from its left half. With `odd`, the last column of the half is the centre.
 * @param {string[]} half @param {boolean} [odd]
 */
export function sym(half, odd = false) {
  return half.map((r) => {
    const m = r.split('').reverse();
    if (odd) m.shift();
    return r + m.join('');
  });
}

/**
 * Pad / crop rows to w x h keeping the bottom-centre anchor.
 * @param {string[]} rows @param {number} w @param {number} h
 */
export function fit(rows, w, h) {
  const rw = rows[0].length;
  const rh = rows.length;
  return place(w, h, rows, Math.floor((w - rw) / 2), h - rh);
}

/** Fill a rectangle on rows. */
export function rect(rows, x, y, w, h, ch) {
  const out = toCells(rows);
  for (let j = y; j < y + h; j++) {
    if (j < 0 || j >= out.length) continue;
    for (let i = x; i < x + w; i++) if (i >= 0 && i < out[j].length) out[j][i] = ch;
  }
  return toRows(out);
}

/** Set single pixels: list of [x, y, ch]. */
export function dots(rows, list) {
  const out = toCells(rows);
  for (const [x, y, ch] of list) if (out[y] && x >= 0 && x < out[y].length) out[y][x] = ch;
  return toRows(out);
}

/** Bounding rows of the non-transparent content: [top, bottom]. */
export function vbounds(rows) {
  let top = -1;
  let bottom = -1;
  rows.forEach((r, i) => {
    if (/[^.]/.test(r)) {
      if (top < 0) top = i;
      bottom = i;
    }
  });
  return [top, bottom];
}

/**
 * Raise one leg by one pixel (fill-space rows, before outlining).
 * @param {string[]} rows
 * @param {{legRows?: number, cx?: number, side: 'L'|'R', legs?: [number, number]}} o legRows = leg height in px from
 *   the bottom; legs = inclusive column range that holds the legs (other columns stay put)
 */
export function raiseLeg(rows, o) {
  const [, bottom] = vbounds(rows);
  const legRows = o.legRows ?? 2;
  const top = bottom - legRows + 1;
  const w = rows[0].length;
  const cx = o.cx ?? Math.floor(w / 2);
  const [x0, x1] = o.legs ?? [0, w - 1];
  const out = toCells(rows);
  for (let x = x0; x <= x1; x++) {
    const inSide = o.side === 'L' ? x < cx : x >= cx;
    if (!inSide) continue;
    for (let y = top; y <= bottom; y++) out[y][x] = y + 1 <= bottom ? rows[y + 1][x] : '.';
  }
  return toRows(out);
}

/**
 * Standard 4-frame walk from a fill-space idle: stand, left step, stand-bob, right step.
 * Returns fill-space frames (outline them afterwards).
 * @param {string[]} rows
 * @param {{legRows?: number, cx?: number, bob?: boolean}} [o]
 */
export function walkFill(rows, o = {}) {
  const l = raiseLeg(rows, { ...o, side: 'L' });
  const r = raiseLeg(rows, { ...o, side: 'R' });
  return [rows, l, rows, r];
}

/**
 * Centre the content of rows inside a w x h box (used for icons).
 * @param {string[]} rows @param {number} [w] @param {number} [h]
 */
export function center(rows, w = rows[0].length, h = rows.length) {
  let x0 = Infinity;
  let x1 = -1;
  let y0 = Infinity;
  let y1 = -1;
  rows.forEach((r, y) => {
    for (let x = 0; x < r.length; x++) {
      if (r[x] === '.') continue;
      x0 = Math.min(x0, x);
      x1 = Math.max(x1, x);
      y0 = Math.min(y0, y);
      y1 = Math.max(y1, y);
    }
  });
  if (x1 < 0) return blank(w, h);
  const part = rows.slice(y0, y1 + 1).map((r) => r.slice(x0, x1 + 1));
  return place(w, h, part, Math.floor((w - part[0].length) / 2), Math.floor((h - part.length) / 2));
}

/**
 * Turn fill frames into finished frames (outline added).
 * @param {string[][]} frames @param {object} [opts] outline options
 */
export function finish(frames, opts) {
  return frames.map((f) => outline(f, opts));
}

