/** All icon sprites, merged into SPRITES by sprites.js. */
export const ICON_SPRITES = (() => {
  const out = {};
  const add = (prefix, set, size, fps = 1) => {
    for (const [k, rows] of Object.entries(set)) out[prefix + k] = { w: size, h: size, fps, anims: { idle: [center(rows, size, size)] } };
  };
  add('spell_', SPELLS, 16);
  add('gadget_', GADGETS, 16);
  add('emote_', EMOTES, 24);
  add('ui_', UI, 10);
  return out;
})();
